    # Calculate district compactness using 4πA/P², where A is district area
    # and P is district perimeter.
    def calculate_compactness(
        self,
        district_geometry
    ):
        if district_geometry is None:
            return 0.0

        if district_geometry.isEmpty():
            return 0.0

        area = (
            district_geometry.area()
        )

        perimeter = (
            district_geometry.length()
        )

        if perimeter == 0:
            return 0.0

        compactness = (
            4
            * math.pi
            * area
        ) / (
            perimeter ** 2
        )

        return compactness

    # Determine whether every Census Block assigned to a district can be
    # reached through touching neighboring blocks.
    def calculate_contiguity(
        self,
        district_number
    ):
        try:
            district_number = int(
                district_number
            )
        except Exception:
            return False

        # Reuse a previous result when district membership has not changed.
        if (
            district_number
            in self.contiguity_cache
        ):
            return (
                self.contiguity_cache[
                    district_number
                ]
            )

        district_features = (
            self.get_district_features(
                district_number
            )
        )

        # A district containing zero or one block cannot be split into
        # multiple disconnected groups.
        if len(district_features) <= 1:
            self.contiguity_cache[
                district_number
            ] = True

            return True

        feature_lookup = {
            feature.id(): feature
            for feature
            in district_features
        }

        # Build a local spatial index so possible neighboring blocks can be
        # found without comparing every possible pair of district blocks.
        spatial_index = (
            QgsSpatialIndex()
        )

        for feature in district_features:
            spatial_index.addFeature(
                feature
            )

        # Perform a graph-style traversal beginning with one district block.
        visited = set()

        stack = [
            district_features[0].id()
        ]

        while stack:
            current_id = (
                stack.pop()
            )

            if current_id in visited:
                continue

            visited.add(
                current_id
            )

            current_feature = (
                feature_lookup[
                    current_id
                ]
            )

            current_geometry = (
                current_feature.geometry()
            )

            # Use the spatial index to find blocks that could touch the
            # current block.
            candidate_ids = (
                spatial_index.intersects(
                    current_geometry.boundingBox()
                )
            )

            for neighbor_id in candidate_ids:
                if neighbor_id == current_id:
                    continue

                if neighbor_id in visited:
                    continue

                neighbor = (
                    feature_lookup.get(
                        neighbor_id
                    )
                )

                if neighbor is None:
                    continue

                neighbor_geometry = (
                    neighbor.geometry()
                )

                if (
                    neighbor_geometry is None
                    or neighbor_geometry.isEmpty()
                ):
                    continue

                # A touching block becomes another node to visit.
                if current_geometry.touches(
                    neighbor_geometry
                ):
                    stack.append(
                        neighbor_id
                    )

        # The district is contiguous only when every district block was
        # reachable from the starting block.
        contiguous = (
            len(visited)
            == len(district_features)
        )

        self.contiguity_cache[
            district_number
        ] = contiguous

        return contiguous

