    # ---------------------------------------------------------------------
    # Dynamic map update
    # ---------------------------------------------------------------------
    # Rebuild the Census Block renderer so map colors represent effective
    # district membership, including temporary reassignments that have not
    # changed the original Census Block attributes.
    def update_map(self):
        if self.blocks_layer is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "Load the redistricting layers before updating the map."
            )
            return

        if self.block_district_field is None:
            return

        district_values = sorted(
            self.district_block_counts.keys()
        )

        if not district_values:
            return

        # Create the root of a rule-based renderer.
        root_rule = (
            QgsRuleBasedRenderer.Rule(
                None
            )
        )

        district_field = (
            QgsExpression.quotedColumnRef(
                self.block_district_field
            )
        )

        for district in district_values:
            conditions = []

            # Begin with the original district assignment stored on the
            # Census Block layer.
            original_condition = (
                f"to_int({district_field}) = "
                f"{int(district)}"
            )

            # Track blocks moved away from or into this district.
            edited_away_ids = []

            edited_into_ids = []

            for feature_id, assigned_district in (
                self.block_district_assignments.items()
            ):
                try:
                    assigned_district = int(
                        assigned_district
                    )
                except Exception:
                    continue

                block = (
                    self.blocks_layer.getFeature(
                        feature_id
                    )
                )

                if not block.isValid():
                    continue

                try:
                    original_district = int(
                        block[
                            self.block_district_field
                        ]
                    )
                except Exception:
                    original_district = None

                if (
                    original_district == district
                    and assigned_district != district
                ):
                    edited_away_ids.append(
                        feature_id
                    )

                if assigned_district == district:
                    edited_into_ids.append(
                        feature_id
                    )

            # Remove blocks that have been reassigned away from this district
            # from the renderer rule based on the original district field.
            if edited_away_ids:
                id_list = ",".join(
                    str(feature_id)
                    for feature_id
                    in edited_away_ids
                )

                original_condition = (
                    f"({original_condition}) "
                    f"AND ($id NOT IN ({id_list}))"
                )

            conditions.append(
                original_condition
            )

            # Add blocks temporarily reassigned into this district.
            if edited_into_ids:
                id_list = ",".join(
                    str(feature_id)
                    for feature_id
                    in edited_into_ids
                )

                conditions.append(
                    f"$id IN ({id_list})"
                )

            district_expression = (
                " OR ".join(
                    f"({condition})"
                    for condition
                    in conditions
                )
            )

            symbol = (
                self.create_district_symbol(
                    district
                )
            )

            rule = (
                QgsRuleBasedRenderer.Rule(
                    symbol
                )
            )

            rule.setFilterExpression(
                district_expression
            )

            rule.setLabel(
                f"District {district}"
            )

            root_rule.appendChild(
                rule
            )

        renderer = (
            QgsRuleBasedRenderer(
                root_rule
            )
        )

        self.blocks_layer.setRenderer(
            renderer
        )

        self.blocks_layer.triggerRepaint()

        # Refresh population labels so they reflect the current district
        # geometries after reassignment or Undo.
        self.update_district_population_display()

        iface.mapCanvas().refresh()

        # Reactivate the custom Census Block selection tool after map tools
        # such as Pan or Zoom may have replaced it.
        iface.mapCanvas().setMapTool(
            self.click_tool
        )

    # ---------------------------------------------------------------------
    # Save completed redistricting plan
    # ---------------------------------------------------------------------
    # Convert the current effective Census Block assignments into one
    # district-level GeoPackage layer containing district geometry,
    # population, and population deviation.
    def save_plan(self):
        if self.blocks_layer is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "Load the redistricting layers before saving."
            )
            return

        file_name, selected_filter = (
            QtWidgets.QFileDialog.getSaveFileName(
                self,
                "Save Redistricting Plan",
                "",
                "GeoPackage (*.gpkg)"
            )
        )

        if not file_name:
            return

        if not file_name.lower().endswith(
            ".gpkg"
        ):
            file_name += ".gpkg"

        crs_authid = (
            self.blocks_layer.crs().authid()
        )

        # Create a temporary district-level polygon layer that will contain
        # one feature for each active district.
        district_layer = QgsVectorLayer(
            f"MultiPolygon?crs={crs_authid}",
            "Redistricting Plan Districts",
            "memory"
        )

        if not district_layer.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "The district output layer could not be created."
            )
            return

        district_provider = (
            district_layer.dataProvider()
        )

        # Store district number, calculated population, and percentage
        # deviation from ideal population in the final output.
        district_provider.addAttributes(
            [
                QgsField(
                    "district",
                    QVariant.Int
                ),
                QgsField(
                    "population",
                    QVariant.Double
                ),
                QgsField(
                    "deviation",
                    QVariant.Double
                )
            ]
        )

        district_layer.updateFields()

        active_districts = sorted(
            self.get_active_districts()
        )

        if active_districts:
            ideal_population = (
                self.total_population
                / len(active_districts)
            )
        else:
            ideal_population = 0.0

        district_features = []

        # Build each saved district from its current effective Census Block
        # geometry rather than from the original district boundary.
        for district in active_districts:
            district_geometry = (
                self.get_district_geometry(
                    district
                )
            )

            if (
                district_geometry is None
                or district_geometry.isEmpty()
            ):
                continue

            # Use the same area-weighted population calculation used by the
            # interactive District Statistics section.
            district_population = (
                self.calculate_district_population(
                    district
                )
            )

            if ideal_population == 0:
                deviation = 0.0
            else:
                deviation = (
                    (
                        district_population
                        - ideal_population
                    )
                    / ideal_population
                ) * 100

            district_feature = QgsFeature(
                district_layer.fields()
            )

            district_feature.setGeometry(
                district_geometry
            )

            district_feature.setAttribute(
                "district",
                int(district)
            )

            district_feature.setAttribute(
                "population",
                district_population
            )

            district_feature.setAttribute(
                "deviation",
                deviation
            )

            district_features.append(
                district_feature
            )

        district_provider.addFeatures(
            district_features
        )

        district_layer.updateExtents()

        # Configure the GeoPackage output.
        district_options = (
            QgsVectorFileWriter.SaveVectorOptions()
        )

        district_options.driverName = "GPKG"
        district_options.layerName = (
            "Redistricting_Plan_Districts"
        )

        # Write the completed district-level plan to disk.
        district_result = (
            QgsVectorFileWriter.writeAsVectorFormatV3(
                district_layer,
                file_name,
                QgsProject.instance().transformContext(),
                district_options
            )
        )

        if (
            district_result[0]
            != QgsVectorFileWriter.WriterError.NoError
        ):
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "The redistricting plan could not be saved."
            )
            return

        # Load the newly saved district layer back into QGIS.
        saved_districts = QgsVectorLayer(
            f"{file_name}|layername=Redistricting_Plan_Districts",
            "Redistricting Plan Districts",
            "ogr"
        )

        if not saved_districts.isValid():
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "The saved district layer could not be loaded."
            )
            return

        # Apply distinct district colors and clear black boundaries.
        categories = []

        colors = self.get_district_colors()

        for index, district in enumerate(
            active_districts
        ):
            symbol = QgsSymbol.defaultSymbol(
                saved_districts.geometryType()
            )

            symbol.setColor(
                colors[
                    index
                    % len(colors)
                ]
            )

            if symbol.symbolLayerCount() > 0:
                symbol.symbolLayer(
                    0
                ).setStrokeColor(
                    QColor("black")
                )

                symbol.symbolLayer(
                    0
                ).setStrokeWidth(
                    0.6
                )

            category = QgsRendererCategory(
                int(district),
                symbol,
                f"District {district}"
            )

            categories.append(
                category
            )

        renderer = QgsCategorizedSymbolRenderer(
            "district",
            categories
        )

        saved_districts.setRenderer(
            renderer
        )

        # Configure labels showing district number and final population.
        settings = QgsPalLayerSettings()

        settings.fieldName = (
            "'District ' || "
            "to_string(\"district\") || "
            "'\\n' || "
            "format_number(\"population\", 0)"
        )

        settings.isExpression = True

        text_format = QgsTextFormat()

        text_format.setSize(
            16
        )

        # Add a black halo around the saved-plan labels.
        buffer_settings = QgsTextBufferSettings()

        buffer_settings.setEnabled(
            True
        )

        buffer_settings.setSize(
            1.2
        )

        buffer_settings.setColor(
            QColor("black")
        )

        text_format.setBuffer(
            buffer_settings
        )

        text_format.setColor(
            QColor("#FDD835")
        )

        settings.setFormat(
            text_format
        )

        # Apply dynamic red/yellow label colors using the saved population
        # deviation field.
        settings.dataDefinedProperties().setProperty(
            QgsPalLayerSettings.Property.Color,
            QgsProperty.fromExpression(
                "CASE "
                "WHEN abs(\"deviation\") > 1.00 "
                "THEN '#FF5252' "
                "ELSE '#FDD835' "
                "END"
            )
        )

        saved_districts.setLabelsEnabled(
            True
        )

        saved_districts.setLabeling(
            QgsVectorLayerSimpleLabeling(
                settings
            )
        )

        # Add the final district-level output to the QGIS project.
        QgsProject.instance().addMapLayer(
            saved_districts
        )

        saved_districts.triggerRepaint()

        iface.mapCanvas().refresh()

        QtWidgets.QMessageBox.information(
            self,
            "Redistricting Editor",
            "Redistricting plan saved successfully."
        )

    # Apply categorized district colors to a layer containing user_dist.
    # Each unique district receives a color from the shared palette and a
    # black boundary outline.
    def apply_district_style(self, layer):
        categories = []
        district_values = []

        # Find all unique district values represented in the layer.
        for feature in layer.getFeatures():
            value = feature[
                "user_dist"
            ]

            if value is None:
                continue

            try:
                value = int(
                    value
                )
            except Exception:
                continue

            if value not in district_values:
                district_values.append(
                    value
                )

        district_values.sort()

        colors = self.get_district_colors()

        # Create one categorized symbol for each district.
        for index, value in enumerate(
            district_values
        ):
            symbol = (
                QgsSymbol.defaultSymbol(
                    layer.geometryType()
                )
            )

            symbol.setColor(
                colors[
                    index
                    % len(colors)
                ]
            )

            symbol.symbolLayer(
                0
            ).setStrokeColor(
                QColor("black")
            )

            symbol.symbolLayer(
                0
            ).setStrokeWidth(
                0.3
            )

            category = (
                QgsRendererCategory(
                    value,
                    symbol,
                    str(value)
                )
            )

            categories.append(
                category
            )

        renderer = (
            QgsCategorizedSymbolRenderer(
                "user_dist",
                categories
            )
        )

        layer.setRenderer(
            renderer
        )

        layer.triggerRepaint()
