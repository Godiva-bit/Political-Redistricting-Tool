    # Find suitable numeric demographic fields in the initialized analysis
    # layer while excluding IDs, district fields, geometry measurements,
    # and the main population field.
    def update_coi_fields(self):
        if self.redistricting_layer is None:
            return

        current_field = (
            self.comboCOIVariable.currentText()
        )

        self.comboCOIVariable.blockSignals(
            True
        )

        self.comboCOIVariable.clear()

        for field in self.redistricting_layer.fields():
            if not field.isNumeric():
                continue

            field_name = field.name()

            normalized_name = (
                field_name
                .lower()
                .replace("_", "")
                .replace(" ", "")
            )

            if normalized_name in (
                "userdist",
                "originaldist",
                "fid",
                "oid",
                "objectid",
                "id"
            ):
                continue

            if "geoid" in normalized_name:
                continue

            if normalized_name.endswith("fp"):
                continue

            if normalized_name in (
                "aland",
                "awater",
                "shapearea",
                "shapelength"
            ):
                continue

            if (
                self.population_field is not None
                and field_name == self.population_field
            ):
                continue

            self.comboCOIVariable.addItem(
                field_name
            )

        # Restore the previously selected COI variable when possible.
        if current_field:
            index = (
                self.comboCOIVariable.findText(
                    current_field
                )
            )

            if index >= 0:
                self.comboCOIVariable.setCurrentIndex(
                    index
                )

        self.comboCOIVariable.blockSignals(
            False
        )

    # Find the analysis unit associated with a selected Census Block.
    # A point on the block surface is transformed into the analysis-layer
    # CRS and tested against candidate analysis units.
    def get_analysis_unit_for_block(
        self,
        block_feature
    ):
        if self.redistricting_layer is None:
            return None

        if block_feature is None:
            return None

        block_geometry = (
            block_feature.geometry()
        )

        if (
            block_geometry is None
            or block_geometry.isEmpty()
        ):
            return None

        # Use a representative point inside the Census Block to associate
        # the block with one analysis unit for local COI reporting.
        representative_point = (
            block_geometry.pointOnSurface()
        )

        analysis_point = (
            self.transform_blocks_geometry_to_analysis(
                representative_point
            )
        )

        if (
            analysis_point is None
            or analysis_point.isEmpty()
        ):
            return None

        # Use the spatial index to reduce the number of analysis features
        # that need to be checked.
        if self.analysis_spatial_index is None:
            candidate_ids = [
                feature.id()
                for feature
                in self.redistricting_layer.getFeatures()
            ]
        else:
            candidate_ids = (
                self.analysis_spatial_index.intersects(
                    analysis_point.boundingBox()
                )
            )

        # Test candidate features and return the analysis unit containing
        # or intersecting the representative point.
        for feature_id in candidate_ids:
            analysis_unit = (
                self.redistricting_layer.getFeature(
                    feature_id
                )
            )

            unit_geometry = (
                analysis_unit.geometry()
            )

            if (
                unit_geometry is None
                or unit_geometry.isEmpty()
            ):
                continue

            if (
                unit_geometry.contains(
                    analysis_point
                )
                or unit_geometry.intersects(
                    analysis_point
                )
            ):
                return analysis_unit

        return None

    # Determine an appropriate denominator for a COI variable when a
    # percentage needs to be calculated.
    def find_coi_denominator_field(
        self,
        value_field
    ):
        if self.redistricting_layer is None:
            return None

        field_index = (
            self.redistricting_layer.fields().indexFromName(
                value_field
            )
        )

        if field_index < 0:
            return None

        field = (
            self.redistricting_layer.fields()[
                field_index
            ]
        )

        descriptor = (
            f"{field.name()} {field.alias()}"
            .lower()
            .replace("_", " ")
        )

        # For unemployment variables, search for the most likely
        # corresponding labor-force denominator.
        if "unemploy" in descriptor:
            best_field = None
            best_score = 0

            for candidate in (
                self.redistricting_layer.fields()
            ):
                if not candidate.isNumeric():
                    continue

                candidate_descriptor = (
                    f"{candidate.name()} {candidate.alias()}"
                    .lower()
                    .replace("_", " ")
                )

                score = 0

                if "labor" in candidate_descriptor:
                    score += 10

                if "force" in candidate_descriptor:
                    score += 10

                if "civilian" in candidate_descriptor:
                    score += 3

                if "unemploy" in candidate_descriptor:
                    score -= 10

                if score > best_score:
                    best_score = score
                    best_field = (
                        candidate.name()
                    )

            if best_score >= 15:
                return best_field

            return None

        # Demographic count variables describing population groups can use
        # the detected total population field as their denominator.
        population_keywords = (
            "black",
            "white",
            "asian",
            "hispanic",
            "latino",
            "race",
            "female",
            "male",
            "population",
            "native",
            "american indian",
            "pacific islander"
        )

        if any(
            keyword in descriptor
            for keyword in population_keywords
        ):
            return self.population_field

        return None

    # Calculate a COI percentage when the selected field already represents
    # a percentage/rate or when a suitable denominator can be identified.
    def calculate_coi_percentage(
        self,
        analysis_unit,
        value_field
    ):
        if analysis_unit is None:
            return None

        try:
            value = float(
                analysis_unit[value_field]
            )
        except Exception:
            return None

        field_index = (
            self.redistricting_layer.fields().indexFromName(
                value_field
            )
        )

        if field_index < 0:
            return None

        field = (
            self.redistricting_layer.fields()[
                field_index
            ]
        )

        descriptor = (
            f"{field.name()} {field.alias()}"
            .lower()
            .replace("_", " ")
        )

        # Handle fields that already represent percentages.
        if (
            "percent" in descriptor
            or "percentage" in descriptor
            or "pct" in descriptor
        ):
            if -1.0 <= value <= 1.0:
                return value * 100.0

            return value

        # Handle rate fields stored either as proportions or percentages.
        if "rate" in descriptor:
            if 0.0 <= value <= 1.0:
                return value * 100.0

            if 0.0 <= value <= 100.0:
                return value

        denominator_field = (
            self.find_coi_denominator_field(
                value_field
            )
        )

        if denominator_field is None:
            return None

        try:
            denominator = float(
                analysis_unit[
                    denominator_field
                ]
            )
        except Exception:
            return None

        if denominator <= 0:
            return None

        return (
            value
            / denominator
        ) * 100.0

    # Display the selected COI value for the analysis unit containing the
    # currently selected Census Block.
    def update_coi_total(self):
        if not self.checkCOI.isChecked():
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        if self.redistricting_layer is None:
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        if self.selected_feature is None:
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        value_field = (
            self.comboCOIVariable.currentText()
        )

        if not value_field:
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        analysis_unit = (
            self.get_analysis_unit_for_block(
                self.selected_feature
            )
        )

        if analysis_unit is None:
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        try:
            value = float(
                analysis_unit[value_field]
            )
        except Exception:
            self.lineCOITotal.clear()
            self.lineCOIPercentage.clear()
            return

        self.lineCOITotal.setText(
            f"{value:,.0f}"
        )

        percentage = (
            self.calculate_coi_percentage(
                analysis_unit,
                value_field
            )
        )

        # Display N/A instead of creating a percentage when the code cannot
        # identify an appropriate denominator.
        if percentage is None:
            self.lineCOIPercentage.setText(
                "N/A"
            )
        else:
            self.lineCOIPercentage.setText(
                f"{percentage:.1f}%"
            )

    # ---------------------------------------------------------------------
    # Layer setup and initialization
    # ---------------------------------------------------------------------
    # Load the three layers selected by the user, validate the required
    # fields, reset the editing session, create the spatial index and caches,
    # calculate initial totals, and activate the Census Block selection tool.
    def load_layer(self):
        existing_districts_layer_id = (
            self.comboExistingDistrictsLayer.currentData()
        )

        analysis_layer_id = (
            self.comboRedistrictingLayer.currentData()
        )

        blocks_layer_id = (
            self.comboBlocksLayer.currentData()
        )

        if (
            existing_districts_layer_id is None
            or analysis_layer_id is None
            or blocks_layer_id is None
        ):
            return

        # Retrieve the selected layers from the current QGIS project.
        self.existing_districts_layer = (
            QgsProject.instance().mapLayer(
                existing_districts_layer_id
            )
        )

        self.redistricting_layer = (
            QgsProject.instance().mapLayer(
                analysis_layer_id
            )
        )

        self.blocks_layer = (
            QgsProject.instance().mapLayer(
                blocks_layer_id
            )
        )

        if self.existing_districts_layer is None:
            return

        if self.redistricting_layer is None:
            return

        if self.blocks_layer is None:
            return

        # Confirm that the analysis layer was initialized for this tool and
        # contains the user_dist field.
        analysis_field_names = [
            field.name()
            for field
            in self.redistricting_layer.fields()
        ]

        if "user_dist" not in analysis_field_names:
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "This layer does not have a user_dist field. "
                "Please use the initialized redistricting layer."
            )

            self.redistricting_layer = None
            return

        # Automatically identify the population field from the initialized
        # analysis layer.
        self.population_field = (
            self.find_population_field()
        )

        if self.population_field is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "A population field could not be identified in the "
                "initialized layer. The population field should be numeric "
                "and have a field name or alias that identifies it as "
                "population."
            )
            return

        # Count the districts represented by the initialized analysis layer.
        self.number_of_districts = (
            self.count_districts()
        )

        # Detect the Census Block field containing the original district ID.
        self.block_district_field = (
            self.find_block_district_field()
        )

        if self.block_district_field is None:
            QtWidgets.QMessageBox.warning(
                self,
                "Redistricting Editor",
                "A district field could not be identified in the Census "
                "Blocks layer. Use a Census Blocks layer containing the "
                "district identifier joined from the Existing Districts "
                "layer."
            )
            return

        # Reset selections and temporary edits when layers are loaded.
        self.selected_feature = None
        self.selected_block_ids = []
        self.edited_feature_ids = []

        self.block_district_assignments = {}
        self.undo_history = []

        self.buttonUndo.setEnabled(
            False
        )

        # Clear previously cached district calculations.
        self.district_block_counts = {}
        self.district_geometry_cache = {}
        self.contiguity_cache = {}

        self.blocks_layer.removeSelection()

        # Build the analysis spatial index once so later population and COI
        # calculations can search nearby features efficiently.
        self.analysis_spatial_index = (
            QgsSpatialIndex(
                self.redistricting_layer.getFeatures()
            )
        )

        # Precalculate total population and district Census Block counts.
        self.calculate_total_population()
        self.build_district_block_counts()

        self.populate_district_combo()
        self.update_coi_fields()
        self.update_ideal_population_display()

        # Clear information left from a previous editing session.
        self.lineSelectedBlocks.setText("0")
        self.lineBlockID.clear()
        self.lineCurrentDistrict.clear()
        self.linePopulation.clear()
        self.lineDistrictPopulation.clear()
        self.lineDeviation.clear()
        self.lineDeviationPeople.clear()
        self.lineCompactness.clear()
        self.lineContiguous.clear()
        self.lineCOITotal.clear()
        self.lineCOIPercentage.clear()

        # Activate the custom Census Block selection tool.
        iface.mapCanvas().setMapTool(
            self.click_tool
        )

        self.update_map()

        QtWidgets.QMessageBox.information(
            self,
            "Redistricting Editor",
            "Layers loaded. Click a Census Block on the map. "
            "Use Ctrl-click on Windows or Command-click on Mac "
            "to select multiple blocks."
        )

    # Identify the most likely total-population field from the initialized
    # analysis layer using field names and aliases.
    def find_population_field(self):
        if self.redistricting_layer is None:
            return None

        best_field = None
        best_score = 0

        for field in self.redistricting_layer.fields():
            if not field.isNumeric():
                continue

            name = field.name().lower()
            alias = field.alias().lower()

            combined = f"{name} {alias}"

            score = 0

            if "population" in combined:
                score += 10

            if "total" in combined:
                score += 5

            normalized_name = (
                name
                .replace("_", "")
                .replace(" ", "")
            )

            if normalized_name in (
                "population",
                "totalpopulation",
                "totalpop",
                "pop"
            ):
                score += 10

            # Avoid selecting fields that represent derived values instead
            # of a total population count.
            if (
                "density" in combined
                or "percent" in combined
                or "percentage" in combined
                or "ratio" in combined
                or "rate" in combined
            ):
                score -= 10

            if score > best_score:
                best_score = score
                best_field = field.name()

        return best_field

    # Identify the district field shared by the Census Blocks and Existing
    # Districts layers. This allows the tool to work without hardcoding a
    # state-specific district field name.
    def find_block_district_field(self):
        if self.blocks_layer is None:
            return None

        if self.existing_districts_layer is None:
            return None

        existing_field_names = {
            field.name()
            for field
            in self.existing_districts_layer.fields()
        }

        candidates = []

        for field in self.blocks_layer.fields():
            field_name = field.name()

            if field_name not in existing_field_names:
                continue

            field_index = (
                self.blocks_layer.fields().indexFromName(
                    field_name
                )
            )

            try:
                values = (
                    self.blocks_layer.dataProvider().uniqueValues(
                        field_index,
                        max(
                            100,
                            self.number_of_districts + 10
                        )
                    )
                )
            except Exception:
                continue

            numeric_values = set()

            for value in values:
                if value is None:
                    continue

                try:
                    numeric_values.add(
                        int(value)
                    )
                except Exception:
                    continue

            if len(numeric_values) <= 1:
                continue

            # Score candidate fields according to their names and whether
            # their number of unique values matches the district count.
            score = 0

            normalized_name = (
                field_name
                .lower()
                .replace("_", "")
                .replace(" ", "")
            )

            if "district" in normalized_name:
                score += 30

            if "dist" in normalized_name:
                score += 20

            if normalized_name.startswith("cd"):
                score += 20

            if (
                self.number_of_districts > 0
                and len(numeric_values)
                == self.number_of_districts
            ):
                score += 50

            elif (
                self.number_of_districts > 0
                and len(numeric_values)
                <= self.number_of_districts + 2
            ):
                score += 20

            candidates.append(
                (
                    score,
                    field_name
                )
            )

        if not candidates:
            return None

        candidates.sort(
            key=lambda item: item[0],
            reverse=True
        )

        return candidates[0][1]

    # Calculate the total population represented by the analysis layer.
    # Geometry is not requested because only the population attribute is
    # required, reducing unnecessary processing.
    def calculate_total_population(self):
        self.total_population = 0.0

        if self.redistricting_layer is None:
            return

        if self.population_field is None:
            return

        request = QgsFeatureRequest()

        population_index = (
            self.redistricting_layer.fields().indexFromName(
                self.population_field
            )
        )

        request.setSubsetOfAttributes(
            [population_index]
        )

        request.setFlags(
            QgsFeatureRequest.NoGeometry
        )

        for feature in (
            self.redistricting_layer.getFeatures(
                request
            )
        ):
            try:
                self.total_population += float(
                    feature[
                        self.population_field
                    ]
                )
            except Exception:
                continue

    # Count how many Census Blocks originally belong to each district.
    # These counts are later adjusted in memory when blocks are reassigned.
    def build_district_block_counts(self):
        self.district_block_counts = {}

        if self.blocks_layer is None:
            return

        if self.block_district_field is None:
            return

        field_index = (
            self.blocks_layer.fields().indexFromName(
                self.block_district_field
            )
        )

        request = QgsFeatureRequest()

        request.setSubsetOfAttributes(
            [field_index]
        )

        request.setFlags(
            QgsFeatureRequest.NoGeometry
        )

        for block in self.blocks_layer.getFeatures(
            request
        ):
            value = block[
                self.block_district_field
            ]

            if value is None:
                continue

            try:
                district = int(value)
            except Exception:
                continue

            if district <= 0:
                continue

            self.district_block_counts[
                district
            ] = (
                self.district_block_counts.get(
                    district,
                    0
                ) + 1
            )

