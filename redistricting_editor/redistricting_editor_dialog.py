# -------------------------------------------------------------------------
# Custom Census Block selection tool
# -------------------------------------------------------------------------
# This map tool allows Census Blocks to be selected directly from the map.
# Ctrl on Windows or Command on Mac allows multiple blocks to be selected.
class RedistrictingClickTool(QgsMapToolIdentify):

    # Initialize the QGIS identify tool and store references to the map
    # canvas and the Redistricting Editor dialog.
    def __init__(self, canvas, dialog):
        QgsMapToolIdentify.__init__(self, canvas)
        self.canvas = canvas
        self.dialog = dialog
        self.setCursor(Qt.CursorShape.PointingHandCursor)

    # Identify the Census Block clicked by the user and send that feature
    # to the editor for single or multiple selection.
    def canvasReleaseEvent(self, event):
        layer = self.dialog.blocks_layer

        if layer is None:
            return

        point = event.pixelPoint()

        results = self.identify(
            point.x(),
            point.y(),
            [layer],
            QgsMapToolIdentify.TopDownStopAtFirst
        )

        if not results:
            return

        feature = results[0].mFeature

        modifiers = event.modifiers()

        # Determine whether Ctrl/Command is being held so the clicked block
        # can be added to or removed from the current multi-selection.
        multi_select = bool(
            modifiers
            & (
                Qt.KeyboardModifier.ControlModifier
                | Qt.KeyboardModifier.MetaModifier
            )
        )

        self.dialog.show_selected_block(
            feature,
            multi_select
        )


