# QGIS and PyQt classes used for plugin settings, translation,
# toolbar/menu actions, icons, and the dockable editor panel.
from qgis.PyQt.QtCore import QLocale, QTranslator, QCoreApplication, Qt
from qgis.core import QgsSettings
from qgis.PyQt.QtGui import QIcon
from qgis.PyQt.QtWidgets import QAction, QDockWidget

# Import the code for the dialog
# The dialog contains the main interactive redistricting functionality.
from .redistricting_editor_dialog import RedistrictingEditorDialog
import os.path


# -------------------------------------------------------------------------
# QGIS plugin controller
# -------------------------------------------------------------------------
# This class connects the Redistricting Editor to the QGIS interface.
# It creates the plugin menu/toolbar action and opens the main editor
# interface inside a dockable QGIS panel.
class RedistrictingEditor:
    """QGIS Plugin Implementation."""

    def __init__(self, iface):
        """Constructor.

        :param iface: An interface instance that will be passed to this class
            which provides the hook by which you can manipulate the QGIS
            application at run time.
        :type iface: QgsInterface
        """
        # Save reference to the QGIS interface
        # This provides access to the main QGIS application window,
        # toolbar, plugin menu, and dock widgets.
        self.iface = iface

        # initialize plugin directory
        # Store the location of this plugin so resources such as translation
        # files and the plugin icon can be found relative to the Python file.
        self.plugin_dir = os.path.dirname(__file__)

        # initialize locale
        # Read the current QGIS language setting and look for a matching
        # translation file in the plugin's i18n directory.
        locale = QgsSettings().value('locale/userLocale', QLocale().name())[0:2]
        locale_path = os.path.join(
            self.plugin_dir,
            'i18n',
            '{}.qm'.format(locale))

        # Install the translation file when one exists for the current locale.
        if os.path.exists(locale_path):
            self.translator = QTranslator()
            self.translator.load(locale_path)
            QCoreApplication.installTranslator(self.translator)

        # Declare instance attributes
        # Keep a list of plugin actions so they can be removed when the
        # plugin is unloaded.
        self.actions = []

        # Name used for the plugin menu inside QGIS.
        self.menu = self.tr(u'&Redistricting Editor')

        # Check if plugin was started the first time in current QGIS session
        # Must be set in initGui() to survive plugin reloads
        self.first_start = None

        # Store the QGIS dock widget that will contain the editor interface.
        # It begins as None and is created the first time the plugin is run.
        self.dock = None

    # ---------------------------------------------------------------------
    # Translation support
    # ---------------------------------------------------------------------
    # Pass plugin interface text through the Qt translation system.
    def tr(self, message):
        """Get the translation for a string using Qt translation API.

        We implement this ourselves since we do not inherit QObject.

        :param message: String for translation.
        :type message: str

        :returns: Translated version of message.
        :rtype: str
        """
        return QCoreApplication.translate('RedistrictingEditor', message)


    # ---------------------------------------------------------------------
    # QGIS menu and toolbar action
    # ---------------------------------------------------------------------
    # Create an action that can be placed in the QGIS Plugins menu,
    # toolbar, or both, and connect it to the requested callback function.
    def add_action(
        self,
        icon_path,
        text,
        callback,
        enabled_flag=True,
        add_to_menu=True,
        add_to_toolbar=True,
        status_tip=None,
        whats_this=None,
        parent=None):
        """Add a toolbar icon to the toolbar.

        :param icon_path: Path to the icon for this action. Can be a resource
            path (e.g. ':/plugins/foo/bar.png') or a normal file system path.
        :type icon_path: str

        :param text: Text that should be shown in menu items for this action.
        :type text: str

        :param callback: Function to be called when the action is triggered.
        :type callback: function

        :param enabled_flag: A flag indicating if the action should be enabled
            by default. Defaults to True.
        :type enabled_flag: bool

        :param add_to_menu: Flag indicating whether the action should also
            be added to the menu. Defaults to True.
        :type add_to_menu: bool

        :param add_to_toolbar: Flag indicating whether the action should also
            be added to the toolbar. Defaults to True.
        :type add_to_toolbar: bool

        :param status_tip: Optional text to show in a popup when mouse pointer
            hovers over the action.
        :type status_tip: str

        :param parent: Parent widget for the new action. Defaults None.
        :type parent: QWidget

        :param whats_this: Optional text to show in the status bar when the
            mouse pointer hovers over the action.

        :returns: The action that was created. Note that the action is also
            added to self.actions list.
        :rtype: QAction
        """

        # Create the icon and QAction displayed by QGIS.
        icon = QIcon(icon_path)
        action = QAction(icon, text, parent)

        # Connect the action to the function that should run when clicked.
        action.triggered.connect(callback)
        action.setEnabled(enabled_flag)

        # Add optional explanatory interface text when provided.
        if status_tip is not None:
            action.setStatusTip(status_tip)

        if whats_this is not None:
            action.setWhatsThis(whats_this)

        if add_to_toolbar:
            # Adds plugin icon to Plugins toolbar
            self.iface.addToolBarIcon(action)

        if add_to_menu:
            # Add the same action to the QGIS Plugins menu.
            self.iface.addPluginToMenu(
                self.menu,
                action)

        # Store the action so it can be removed cleanly when the plugin
        # is unloaded.
        self.actions.append(action)

        return action

    # ---------------------------------------------------------------------
    # Plugin interface initialization
    # ---------------------------------------------------------------------
    # Create the Redistricting Editor action when QGIS loads the plugin.
    def initGui(self):
        """Create the menu entries and toolbar icons inside the QGIS GUI."""

        # Locate the plugin icon stored in the plugin directory.
        icon_path = os.path.join(os.path.dirname(__file__), 'icon.png')

        # Create the action that opens the Redistricting Editor.
        self.add_action(
            icon_path,
            text=self.tr(u'Redistricting editor'),
            callback=self.run,
            parent=self.iface.mainWindow())

        # will be set False in run()
        self.first_start = True


    # ---------------------------------------------------------------------
    # Plugin cleanup
    # ---------------------------------------------------------------------
    # Remove plugin actions and close the editor dock when QGIS unloads
    # or reloads the plugin.
    def unload(self):
        """Removes the plugin menu item and icon from QGIS GUI."""

        # Remove every action previously added to the QGIS menu and toolbar.
        for action in self.actions:
            self.iface.removePluginMenu(
                self.tr(u'&Redistricting Editor'),
                action)
            self.iface.removeToolBarIcon(action)
            
        # Close the dockable editor panel if it currently exists.
        if self.dock is not None:
            self.dock.close()
            self.dock = None

    # ---------------------------------------------------------------------
    # Open the Redistricting Editor
    # ---------------------------------------------------------------------
    # Create the editor dialog and place it inside a dockable QGIS panel.
    # If the dock already exists, reuse it instead of creating another one.
    def run(self):
        """Open the redistricting editor panel."""

        # Create the dialog and dock only the first time the plugin is opened.
        if self.dock is None:

            # RedistrictingEditorDialog contains the main editing,
            # statistics, map-update, and save-plan functionality.
            self.dlg = RedistrictingEditorDialog()

            # Place the editor interface inside a QGIS dock widget.
            self.dock = QDockWidget("Redistricting Editor")
            self.dock.setWidget(self.dlg)

            # Display the dock on the right side of the main QGIS window.
            self.iface.addDockWidget(Qt.DockWidgetArea.RightDockWidgetArea, self.dock)

        # Show the existing dock again if it was previously hidden.
        self.dock.show()
